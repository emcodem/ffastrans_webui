'use strict';
/*
 * Packs an app into a nexe base binary (see build_base.bat / sea-boot.js), replacing the nexe CLI.
 * Writes the same layout nexe 4.0.0-rc.7 writes, byte for byte:
 *   [base binary][boot code][resources][<nexe~~sentinel>][code size: double LE][resources size: double LE]
 * The boot code is the resource index plus nexe's fs shim (nexe-fs-patch.js, MIT, see NEXE_LICENSE),
 * which sea-boot.js reads and runs at startup.
 *
 * Usage (cwd = directory containing the entry):
 *   node pack.js --base <base binary> --entry server.js --out server.exe
 *                --include <dir> [--include <dir> ...] [--exclude <dir> ...]
 * Includes all files below each --include dir like nexe's "-r dir/**": files only, names starting
 * with "." are skipped (glob default). --exclude skips a directory relative to cwd.
 */
const fs = require('fs');
const path = require('path');

function parseArgs(argv) {
    const args = { include: [], exclude: [] };
    for (let i = 0; i < argv.length; i += 2) {
        const key = argv[i].replace(/^--/, ''), value = argv[i + 1];
        if (value === undefined) throw new Error('missing value for ' + argv[i]);
        if (key === 'include' || key === 'exclude') args[key].push(value);
        else args[key] = value;
    }
    for (const required of ['base', 'entry', 'out']) {
        if (!args[required]) throw new Error('missing --' + required);
    }
    return args;
}

function collectFiles(cwd, includes, excludes) {
    const excluded = excludes.map(e => path.resolve(cwd, e));
    const files = [];
    function walk(dir) {
        if (excluded.includes(dir)) return;
        for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
            if (entry.name.startsWith('.')) continue;
            const full = path.join(dir, entry.name);
            if (entry.isDirectory()) walk(full);
            else if (entry.isFile()) files.push(full);
        }
    }
    for (const inc of includes) {
        const dir = path.resolve(cwd, inc);
        if (fs.existsSync(dir)) walk(dir);
    }
    return files;
}

function main() {
    const args = parseArgs(process.argv.slice(2));
    const cwd = process.cwd();
    const wrap = code => '!(function () {' + code + '})();';

    // resources: entry + included files, deduplicated and sorted by absolute path like nexe's bundle index
    const absFiles = [...new Set([path.resolve(cwd, args.entry), ...collectFiles(cwd, args.include, args.exclude)])]
        .sort((a, b) => (a > b ? 1 : -1));
    const resources = {};
    let offset = 0;
    for (const file of absFiles) {
        const size = fs.statSync(file).size;
        resources['./' + path.relative(cwd, file)] = [offset, size];
        offset += size;
    }
    const resourcesSize = offset;

    // boot code, as generated by nexe's shim step
    const fsPatch = fs.readFileSync(path.join(__dirname, 'nexe-fs-patch.js'), 'utf8').replace(/\r\n/g, '\n');
    const entry = './' + path.relative(cwd, path.resolve(cwd, args.entry));
    const code =
        wrap('process.__nexe = ' + JSON.stringify({ resources }) + ';\n') +
        wrap(fsPatch + '\nshimFs(process.__nexe)' + '\n') +
        wrap('\n    if (process.argv[1] && process.env.NODE_UNIQUE_ID) {\n      const cluster = require(\'cluster\')\n      cluster._setupWorker()\n      delete process.env.NODE_UNIQUE_ID\n    }\n  ') +
        wrap('\n      if (!process.send) {\n        const path = require(\'path\')\n        const entry = path.resolve(path.dirname(process.execPath),' + JSON.stringify(entry) + ')\n        process.argv.splice(1,0, entry)\n      }\n    ') +
        ';';

    const footer = Buffer.alloc(32);
    footer.write('<nexe~~sentinel>', 0, 'latin1');
    footer.writeDoubleLE(Buffer.byteLength(code), 16);
    footer.writeDoubleLE(resourcesSize, 24);

    const out = fs.openSync(args.out, 'w');
    try {
        fs.writeSync(out, fs.readFileSync(args.base));
        fs.writeSync(out, code);
        for (const file of absFiles) fs.writeSync(out, fs.readFileSync(file));
        fs.writeSync(out, footer);
    } finally {
        fs.closeSync(out);
    }
    console.log(`packed ${absFiles.length} files (${resourcesSize} bytes) into ${args.out}`);
}

main();
